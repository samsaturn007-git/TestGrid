package dev.testgrid.api.crash;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import java.util.concurrent.ConcurrentHashMap;
import org.junit.jupiter.api.extension.AfterAllCallback;
import org.junit.jupiter.api.extension.BeforeTestExecutionCallback;
import org.junit.jupiter.api.extension.ExtensionContext;
import org.junit.jupiter.api.extension.TestWatcher;

/**
 * Writes the PRD-04 Verification record ("repeat each crash test 5 times and record pass counts")
 * to target/evidence/prd04-crash-tests.txt: per test method, passes and failures, durations, and
 * whatever measurements the test noted. Surefire's XML holds the same pass/fail data.
 */
public final class EvidenceRecorder
    implements BeforeTestExecutionCallback, TestWatcher, AfterAllCallback {

  static final Path FILE = Path.of("target/evidence/prd04-crash-tests.txt");

  private record Tally(List<String> runs, List<String> notes) {}

  private static final Map<String, Tally> TALLIES = new ConcurrentHashMap<>();
  private static final ThreadLocal<Long> STARTED = new ThreadLocal<>();
  private static final ThreadLocal<String> CURRENT = new ThreadLocal<>();

  /** Adds a measurement to the current test's record. */
  static void note(String text) {
    String key = CURRENT.get();
    if (key != null) {
      tally(key).notes().add(text);
    }
  }

  private static Tally tally(String key) {
    return TALLIES.computeIfAbsent(
        key,
        k ->
            new Tally(
                java.util.Collections.synchronizedList(new ArrayList<>()),
                java.util.Collections.synchronizedList(new ArrayList<>())));
  }

  private static String key(ExtensionContext context) {
    return context.getRequiredTestClass().getSimpleName()
        + "."
        + context.getRequiredTestMethod().getName();
  }

  @Override
  public void beforeTestExecution(ExtensionContext context) {
    STARTED.set(System.nanoTime());
    CURRENT.set(key(context));
  }

  private void record(ExtensionContext context, String outcome) {
    long ms = (System.nanoTime() - STARTED.get()) / 1_000_000;
    tally(key(context)).runs().add(outcome + " " + ms + " ms");
    CURRENT.remove();
  }

  @Override
  public void testSuccessful(ExtensionContext context) {
    record(context, "PASS");
  }

  @Override
  public void testFailed(ExtensionContext context, Throwable cause) {
    record(context, "FAIL (" + cause.getClass().getSimpleName() + ")");
  }

  @Override
  public void testAborted(ExtensionContext context, Throwable cause) {
    record(context, "ABORTED");
  }

  @Override
  public void testDisabled(ExtensionContext context, Optional<String> reason) {}

  @Override
  public void afterAll(ExtensionContext context) {
    StringBuilder out = new StringBuilder("# PRD-04 crash tests (generated by EvidenceRecorder)\n");
    new TreeMap<>(TALLIES)
        .forEach((test, tally) -> {
          long passes = tally.runs().stream().filter(r -> r.startsWith("PASS")).count();
          out.append("\n")
              .append(test)
              .append(": ")
              .append(passes)
              .append("/")
              .append(tally.runs().size())
              .append(" passed\n");
          tally.runs().forEach(r -> out.append("  run: ").append(r).append('\n'));
          tally.notes().forEach(n -> out.append("  note: ").append(n).append('\n'));
        });
    try {
      Files.createDirectories(FILE.getParent());
      Files.writeString(FILE, out);
    } catch (IOException e) {
      throw new UncheckedIOException(e);
    }
  }
}

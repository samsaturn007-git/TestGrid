-- PRD-06 FR-2/FR-3: artifacts (contracts §3, ADR-005). Bytes live in the ArtifactStore under
-- storage_key; this row is the source of truth for what exists and whether it may be read.

CREATE TABLE artifacts (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  attempt_id     uuid NOT NULL REFERENCES attempts (id),
  -- The case the worker named on upload (checked against the claim). The completion transaction
  -- links case_result_id from it, because case results don't exist before then (CONFLICT_REGISTER N20).
  case_key       text NULL CHECK (case_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(case_key) <= 64),
  case_result_id uuid NULL REFERENCES case_results (id),
  kind           text NOT NULL CHECK (kind IN ('SCREENSHOT', 'TRACE', 'LOG')),
  mime           text NOT NULL CHECK (mime IN ('image/png', 'application/zip', 'text/plain; charset=utf-8')),
  -- Generated by the server; the same pattern ArtifactKeys enforces.
  storage_key    text NOT NULL UNIQUE CHECK (storage_key ~
    '^[0-9]{4}/(0[1-9]|1[0-2])/(0[1-9]|[12][0-9]|3[01])/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(png|zip|log)$'),
  byte_size      bigint NOT NULL CHECK (byte_size BETWEEN 1 AND 52428800),
  sha256         text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  state          text NOT NULL DEFAULT 'AVAILABLE' CHECK (state IN ('AVAILABLE', 'EXPIRED', 'MISSING', 'PURGED')),
  expires_at     timestamptz NOT NULL,
  version        integer NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT artifacts_kind_mime CHECK (
    (kind = 'SCREENSHOT' AND mime = 'image/png') OR
    (kind = 'TRACE' AND mime = 'application/zip') OR
    (kind = 'LOG' AND mime = 'text/plain; charset=utf-8')),
  CONSTRAINT artifacts_kind_size CHECK (
    (kind = 'SCREENSHOT' AND byte_size <= 5242880) OR
    (kind = 'TRACE' AND byte_size <= 52428800) OR
    (kind = 'LOG' AND byte_size <= 1048576)),
  CONSTRAINT artifacts_expires_after_created CHECK (expires_at > created_at)
);

-- Required indexes (contracts §3).
CREATE INDEX artifacts_attempt ON artifacts (attempt_id);
CREATE INDEX artifacts_expiring ON artifacts (expires_at) WHERE state = 'AVAILABLE';

-- What was stored never changes. Only two things may: case_result_id is filled in once, and state
-- moves forward (AVAILABLE -> EXPIRED -> PURGED, or to MISSING when the bytes are gone).
CREATE FUNCTION artifacts_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'artifacts rows are kept; set state instead'
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF (to_jsonb(NEW) - 'case_result_id' - 'state' - 'version')
       IS DISTINCT FROM (to_jsonb(OLD) - 'case_result_id' - 'state' - 'version') THEN
    RAISE EXCEPTION 'artifact % content is immutable', OLD.id USING ERRCODE = 'restrict_violation';
  END IF;
  IF OLD.case_result_id IS NOT NULL AND NEW.case_result_id IS DISTINCT FROM OLD.case_result_id THEN
    RAISE EXCEPTION 'artifact % is already linked to a case result', OLD.id
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW.state IS DISTINCT FROM OLD.state AND NOT (
       (OLD.state = 'AVAILABLE' AND NEW.state IN ('EXPIRED', 'MISSING')) OR
       (OLD.state = 'EXPIRED' AND NEW.state IN ('PURGED', 'MISSING'))) THEN
    RAISE EXCEPTION 'artifact % cannot move from % to %', OLD.id, OLD.state, NEW.state
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER artifacts_guarded
  BEFORE UPDATE OR DELETE ON artifacts
  FOR EACH ROW EXECUTE FUNCTION artifacts_guard();
